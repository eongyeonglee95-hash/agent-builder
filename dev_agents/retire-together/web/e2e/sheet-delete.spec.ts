import { expect, test, type APIRequestContext, type Page } from '@playwright/test'

async function addAsset(request: APIRequestContext, name: string) {
  const response = await request.post('/api/assets', { data: {
    request_id: crypto.randomUUID(), name, account: name + ' 계좌', owner: 'me',
    pocket: 'retirement', assetClass: 'mixed', amount: 0, as_of: '2026-11-01',
  } })
  expect(response.ok(), await response.text()).toBe(true)
  return response.json()
}
async function openAssets(page: Page) {
  await page.goto('/#assets')
  await page.getByRole('button', { name: '자산 등록', exact: true }).first().click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: /표로 입력/ }).click()
  await dialog.getByRole('tab', { name: '자산', exact: true }).click()
  await expect(dialog.getByRole('grid', { name: '자산 표' })).toBeVisible()
  return dialog
}

test('등록 창: 확인 즉시 선택한 자산만 삭제하고 다른 미저장 수정은 보존한다', async ({ page, request }) => {
  const target = await addAsset(request, '삭제 대상 보험')
  const keep = await addAsset(request, '남겨둘 보험')
  const dialog = await openAssets(page)
  // A pending edit must neither be saved nor discarded by deleting another row.
  const grid = dialog.getByRole('grid', { name: '자산 표' })
  const keepCell = grid.getByRole('gridcell', { name: '남겨둘 보험', exact: true })
  const keepIndex = await keepCell.evaluate(el => [...el.parentElement!.querySelectorAll('.xl-cell')].indexOf(el))
  await grid.locator('.xl-cell').nth(keepIndex + 7).click()
  await page.keyboard.type('123456')
  await page.keyboard.press('Enter')
  await dialog.getByRole('gridcell', { name: '삭제 대상 보험', exact: true }).click()
  await dialog.getByRole('button', { name: '선택 행 삭제', exact: true }).click()
  const confirm = dialog.getByRole('group', { name: '행 삭제 확인' })
  await expect(confirm).toContainText('삭제 대상 보험')
  await confirm.getByRole('button', { name: '취소', exact: true }).click()
  expect((await (await request.get('/api/assets')).json()).some((a: {id: string}) => a.id === target.id)).toBe(true)
  await dialog.getByRole('button', { name: '선택 행 삭제', exact: true }).click()
  await confirm.getByRole('button', { name: '삭제하기', exact: true }).click()
  await expect(dialog.getByRole('gridcell', { name: '삭제 대상 보험', exact: true })).toHaveCount(0)
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('gridcell', { name: '123,456', exact: true })).toBeVisible()
  await expect(dialog.locator('.xl-status')).toContainText('바뀐 줄 1개')
  const saved = await (await request.get('/api/assets')).json()
  expect(saved.some((a: {id: string}) => a.id === target.id)).toBe(false)
  expect(saved.find((a: {id: string}) => a.id === keep.id).amount).toBe(0)
  await dialog.locator('.xl-save').click()
  await expect(dialog).toBeHidden()
  expect((await (await request.get('/api/assets')).json()).find((a: {id: string}) => a.id === keep.id).amount).toBe(123456)
  const reopened = await openAssets(page)
  await expect(reopened.getByRole('gridcell', { name: '삭제 대상 보험', exact: true })).toHaveCount(0)
  await reopened.getByRole('gridcell', { name: '남겨둘 보험', exact: true }).click()
  for (const width of [1440, 390, 360]) {
    await page.setViewportSize({ width, height: 844 })
    await expect(reopened.getByRole('button', { name: '선택 행 삭제', exact: true })).toBeInViewport()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: test.info().outputPath(`asset-delete-${width}.png`) })
  }
})

test('Delete 키도 확인을 거치며 서버 충돌은 표시하고 원래 자산을 유지한다', async ({ page, request }) => {
  const target = await addAsset(request, '충돌 검수 보험')
  await page.goto('/#sheet-assets')
  const grid = page.getByRole('grid', { name: '자산 표' })
  const cell = grid.getByRole('gridcell', { name: '충돌 검수 보험', exact: true })
  await cell.click()
  const index = await cell.evaluate(el => [...el.parentElement!.querySelectorAll('.xl-cell')].indexOf(el))
  const width = await grid.locator('.xl-head').count()
  await grid.getByRole('rowheader').nth(Math.floor(index / width)).click()
  await page.keyboard.press('Delete')
  const confirm = page.getByRole('group', { name: '행 삭제 확인' })
  await expect(confirm).toContainText('충돌 검수 보험')
  await page.route(`**/api/assets/${target.id}?version=*`, route => route.fulfill({ status: 409, json: { detail: '다른 화면에서 변경한 자산입니다. 새 값을 확인해 주세요.' } }))
  await confirm.getByRole('button', { name: '삭제하기', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('다른 화면에서 변경한 자산')
  expect((await (await request.get('/api/assets')).json()).some((a: {id: string}) => a.id === target.id)).toBe(true)
  await expect(cell).toBeVisible()
  await expect(confirm.getByRole('button', { name: '삭제하기', exact: true })).toBeEnabled()
  await page.unroute(`**/api/assets/${target.id}?version=*`)
  await confirm.getByRole('button', { name: '삭제하기', exact: true }).click()
  await expect(cell).toHaveCount(0)
  await expect(page.locator('.xl-save')).toBeDisabled()
})

test('가져온 자산은 안내하고 보유종목 탭에서 선택한 종목을 삭제한다', async ({ page, request }) => {
  const account = await (await request.post('/api/register/accounts', { data: { label: '종목 삭제 검수', owner: 'me', broker: 'mirae', account_type: 'pension_savings' } })).json()
  const committed = await request.post('/api/register/commit', { data: { account_id: account.id, source: 'file', as_of: '2026-11-01', accept_diff: true,
    rows: [{ ticker_name: '삭제할 ETF', ticker: '069500', qty: 2, price: 10000, asset_class: 'stock' }, { ticker_name: '남길 ETF', ticker: '453850', qty: 3, price: 10000, asset_class: 'long_bond' }] } })
  expect(committed.ok()).toBe(true)
  await page.goto('/#sheet-assets')
  const grid = page.getByRole('grid', { name: '자산 표' })
  await grid.locator('.xl-cell.ro').first().click()
  await expect(page.getByRole('button', { name: '선택 행 삭제', exact: true })).toBeDisabled()
  await expect(page.getByText('사진·파일로 가져온 자산은 보유종목 탭에서 수정·삭제해요.', { exact: true })).toBeVisible()
  await page.getByRole('tab', { name: '보유종목', exact: true }).click()
  const holdings = page.getByRole('grid', { name: '보유종목 표' })
  const keepIndex = await holdings.getByRole('gridcell', { name: '남길 ETF', exact: true }).evaluate(el => [...el.parentElement!.querySelectorAll('.xl-cell')].indexOf(el))
  await holdings.locator('.xl-cell').nth(keepIndex + 2).click()
  await page.keyboard.type('7')
  await page.keyboard.press('Enter')
  await page.getByRole('gridcell', { name: '삭제할 ETF', exact: true }).click()
  await page.getByRole('button', { name: '선택 행 삭제', exact: true }).click()
  await page.getByRole('group', { name: '행 삭제 확인' }).getByRole('button', { name: '삭제하기', exact: true }).click()
  await expect(page.getByRole('gridcell', { name: '삭제할 ETF', exact: true })).toHaveCount(0)
  await expect(page.getByRole('gridcell', { name: '남길 ETF', exact: true })).toBeVisible()
  const result = await (await request.get('/api/register/sheet?owner=together')).json()
  expect(result.rows.filter((r: {account_id: string}) => r.account_id === account.id).map((r: {ticker_name: string}) => r.ticker_name)).toEqual(['남길 ETF'])
  expect(result.rows.find((r: {account_id: string}) => r.account_id === account.id).qty).toBe(3)
  expect(result.as_of[account.id]).toBe('2026-11-01')
  await expect(holdings.getByRole('gridcell', { name: '7', exact: true })).toBeVisible()
  await page.locator('.xl-save').click()
  await expect(page.locator('.xl-status')).toContainText('바뀐 내용 없음')
  const after = await (await request.get('/api/register/sheet?owner=together')).json()
  expect(after.rows.find((r: {account_id: string}) => r.account_id === account.id).qty).toBe(7)

})
