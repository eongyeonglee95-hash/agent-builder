test('생활비 계산: 입력 검증·저장 오류·버전 충돌에 초안과 기존 목표 유지', async ({ page, request }) => {
  await page.goto('/#pension')
  await page.getByRole('button', { name: '생활비 계산', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '생활비 계산', exact: true })
  const apply = dialog.getByRole('button', { name: /생활비 목표로 적용/ })
  const people = dialog.getByRole('spinbutton', { name: '식사 인원', exact: true })
  for (const invalid of ['', '0', '1.5', '11']) {
    await people.fill(invalid)
    await expect(apply).toBeDisabled()
    await expect(dialog.getByTestId('budget-total')).toHaveText('—')
  }
  await people.fill('2')
  await dialog.getByRole('spinbutton', { name: '병원·약값', exact: true }).fill('70')
  await page.route('**/api/retirement/plan', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: '생활비 저장 검수 오류' }) }))
  await apply.click()
  await expect(dialog.getByRole('alert')).toContainText('적용하지 못했어요')
  await expect(dialog.getByTestId('budget-total')).toHaveText('770')
  await expect(apply).toBeEnabled()
  await page.unroute('**/api/retirement/plan')
  const { plan } = await (await request.get('/api/retirement')).json()
  expect(plan.monthly_need).toBe(5000000)
  expect((await request.put('/api/retirement/plan', { data: { ...plan, monthly_need: 4500000 } })).ok()).toBe(true)
  await apply.click()
  await expect(dialog.getByRole('alert')).toContainText('다른 화면에서 계획을 바꿨다면')
  await expect(dialog.getByTestId('budget-total')).toHaveText('770')
  expect((await (await request.get('/api/retirement')).json()).plan.monthly_need).toBe(4500000)
})

test('생활비 계산: 개인 보기에서도 부부 목표·모바일 편집과 저장 버튼 접근', async ({ page }) => {
  await page.goto('/#sheet-retire')
  await page.getByRole('group', { name: '연금 조회 범위' }).getByRole('button', { name: '배우자', exact: true }).click()
  await page.getByRole('button', { name: '생활비 계산', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '생활비 계산', exact: true })
  await expect(dialog).toContainText('오늘 돈 · 부부 합계')
  for (const width of [1440, 768, 390, 360]) {
    await page.setViewportSize({ width, height: 844 })
    expect(await dialog.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    await expect(dialog.getByRole('button', { name: '월 750만 원을 생활비 목표로 적용', exact: true })).toBeInViewport()
    const other = dialog.getByRole('spinbutton', { name: '기타·대출·교육비', exact: true })
    await other.fill('20')
    await expect(dialog.getByTestId('budget-total')).toHaveText('770')
    await other.fill('0')
  }
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: '생활비 계산', exact: true })).toBeFocused()
})

