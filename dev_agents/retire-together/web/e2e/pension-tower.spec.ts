  const initial = await seed(request)
  expect((await request.post('/api/assets', { data: { request_id: crypto.randomUUID(), name: '연금탑 적립금 검수', account: '검수 개인연금저축', owner: 'me', pocket: 'retirement', assetClass: 'mixed', amount: 60000000, as_of: new Date().toISOString().slice(0, 10) } })).ok()).toBe(true)
