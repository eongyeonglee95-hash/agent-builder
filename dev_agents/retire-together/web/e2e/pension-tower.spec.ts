import { expect, test, type APIRequestContext } from '@playwright/test'

async function seed(request: APIRequestContext) {
  const family = await (await request.get('/api/family')).json()
  expect((await request.put('/api/family', { data: { me: { name: '연금탑 검수', age: 40 }, partner: { name: '연금탑 배우자', age: 43 }, retirement_age: 60, target_amount: null, version: family?.version ?? 0 } })).ok()).toBe(true)
  const before = await (await request.get('/api/retirement')).json()
  const response = await request.put('/api/retirement/plan', { data: { me: { national_monthly: 1200000, national_start_age: 65, retire_age: 60, private_start_age: 60, db_accrued: 36000000, savings_annual: 1200000 }, partner: { national_monthly: 800000, national_start_age: 65, retire_age: 63, private_start_age: 63 }, monthly_need: 3500000, return_rate: 0, inflation: 0, version: before.plan.version } })
  expect(response.ok()).toBe(true)
  return response.json()
}

test('연금탑: 서버 합계·부부 나이·개인 범위·입력 저장·다른 보기·새로고침', async ({ page, request }) => {
  const data = await seed(request)
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/#sheet-retire')
  await expect(page.getByRole('heading', { name: '노후 주머니' })).toBeVisible()
  const year = data.base_year + 25
  const slider = page.getByRole('slider', { name: '살펴보는 연도' })
  await slider.fill(String(year))
  const row = data.projection.rows.find((r: { year: number }) => r.year === year)
  await expect(page.getByTestId('pension-total')).toHaveAttribute('data-won', String(row.total_real))
  await expect(page.locator('.tower-summary-ages')).toHaveText('나 65세 · 배우자 68세')
  await expect(page.getByRole('button', { name: '4층 추가연금 살펴보기', exact: true })).toContainText('수령 계산 미연결')
  await page.getByRole('group', { name: '연금 조회 범위' }).getByRole('button', { name: '배우자', exact: true }).click()
  const partner = row.items.filter((i: { person: string }) => i.person === 'partner').reduce((sum: number, i: { real: number }) => sum + i.real, 0)
  await expect(page.getByTestId('pension-total')).toHaveAttribute('data-won', String(partner))
  await expect(page.locator('.tower-gap')).toContainText('생활비는 부부의 합계와 비교해요')
  await expect(page.locator('.tower-coverage-label')).not.toContainText('충당')
  await page.getByRole('group', { name: '연금 조회 범위' }).getByRole('button', { name: '우리 함께', exact: true }).click()
  await page.getByRole('button', { name: '1층 국민연금 살펴보기', exact: true }).click()
  await page.getByRole('button', { name: '국민연금 입력하기', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '국민연금 입력', exact: true })
  await dialog.getByRole('spinbutton', { name: '나 예상 연금 월액', exact: true }).fill('1500000')
  await dialog.getByRole('button', { name: '저장하고 다시 계산', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByTestId('pension-total')).toHaveAttribute('data-won', String(row.total_real + 300000))
  const after = await (await request.get('/api/retirement')).json()
  expect(after.plan.me.national_monthly).toBe(1500000)
  expect(after.plan.partner.national_monthly).toBe(800000)
  // Stop together at the older person's model horizon, not an apparent pension cut.
  expect(Number(await slider.getAttribute('max'))).toBe(data.base_year + data.assumptions.end_age - 43 - 1)
  await page.reload()
  await expect(page.getByRole('heading', { name: '노후 주머니' })).toBeVisible()
  await expect(page).toHaveURL(/#sheet-retire$/)
  await page.goto('/#pension')
  await page.getByRole('slider', { name: '살펴보는 연도' }).fill(String(year))
  await expect(page.getByTestId('pension-total')).toHaveAttribute('data-won', String(row.total_real + 300000))
  for (const width of [1440, 1024, 768, 390, 360]) {
    await page.setViewportSize({ width, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await expect(page.getByRole('button', { name: '4층 추가연금 살펴보기', exact: true })).toBeVisible()
  }
  await page.locator('.tower-tier').nth(2).focus()
  await page.keyboard.press('Enter')
  await expect(page.locator('.tower-detail h2')).toHaveText('3층 · 개인연금')
  await page.getByRole('button', { name: '개인연금 입력하기', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '개인연금 입력', exact: true })).toBeInViewport()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '내 정보', exact: true }).click()
  const profile = page.getByRole('dialog', { name: '내 정보 · 배우자 정보', exact: true })
  await profile.locator('[name="me-age"]').fill('41')
  await profile.getByRole('button', { name: '내 정보 저장', exact: true }).click()
  await expect(profile).toBeHidden()
  await expect(page.locator('.tower-summary-ages')).toHaveText('나 66세 · 배우자 68세')
  expect((await (await request.get('/api/family')).json()).me.age).toBe(41)
  expect(errors).toEqual([])
})

test('연금탑: 저장 실패는 초안을 유지하고, 불완전한 가족·조회 실패를 정상 금액으로 표시하지 않는다', async ({ page, request }) => {
  const data = await seed(request)
  await page.goto('/#sheet-retire')
  await page.getByRole('button', { name: '국민연금 입력하기', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '국민연금 입력', exact: true })
  await dialog.getByRole('spinbutton', { name: '나 예상 연금 월액', exact: true }).fill('1900000')
  await page.route('**/api/retirement/plan', route => route.fulfill({ status: 409, contentType: 'application/json', body: JSON.stringify({ detail: '다른 화면에서 은퇴 계획이 바뀌었어요.' }) }))
  await dialog.getByRole('button', { name: '저장하고 다시 계산', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('저장하지 못했어요')
  await expect(dialog.getByRole('spinbutton', { name: '나 예상 연금 월액', exact: true })).toHaveValue('1900000')
  expect((await (await request.get('/api/retirement')).json()).plan.me.national_monthly).toBe(1200000)
  await dialog.getByRole('button', { name: '취소', exact: true }).click()
  await page.unroute('**/api/retirement/plan')
  const partial = { ...data, missing: ['배우자 나이'], used: { me: data.used.me } }
  await page.route('**/api/retirement', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify(partial) }))
  await page.reload()
  await expect(page.locator('.tower-alert')).toContainText('배우자 나이')
  await expect(page.locator('.tower-coverage-label')).not.toContainText('충당')
  await page.unroute('**/api/retirement')
  await page.route('**/api/retirement', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: '조회 연결을 확인해 주세요.' }) }))
  await page.reload()
  await expect(page.getByRole('heading', { name: '연금 계획을 불러오지 못했어요' })).toBeVisible()
  await expect(page.getByTestId('pension-total')).toHaveCount(0)
  await page.unroute('**/api/retirement')
  await page.getByRole('button', { name: '다시 불러오기', exact: true }).click()
  await expect(page.getByRole('heading', { name: '노후 주머니' })).toBeVisible()
})

