test('개인연금: 잘못된 기간·미리보기 실패는 저장을 막고 재시도한다', async ({ page, request }) => {
  const initial = await seed(request)
  await page.goto('/#pension')
  await page.getByRole('button', { name: '미래 납입 계획', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '개인연금 미래 납입 계획' })
  const save = dialog.getByRole('button', { name: '나 계획 저장' })
  await dialog.getByLabel('납입 종료 나이').fill('61')
  await expect(dialog.getByRole('alert')).toContainText('연금 수령 시작 나이')
  await expect(save).toBeDisabled()
  await expect(dialog.getByTestId('savings-principal')).toHaveCount(0)
  await dialog.getByLabel('납입 종료 나이').fill('55')
  await expect(save).toBeEnabled()
  await page.route('**/api/retirement/preview', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: '미리보기 검수 오류' }) }))
  await dialog.getByLabel('매년 납입할 금액').fill('700')
  await expect(dialog.getByRole('alert')).toContainText('미리보기 검수 오류')
  await expect(dialog.getByTestId('savings-principal')).toHaveCount(0)
  await expect(save).toBeDisabled()
  await page.unroute('**/api/retirement/preview')
  await dialog.getByRole('button', { name: '다시 계산' }).click()
  await expect(save).toBeEnabled()
  await expect(dialog.getByTestId('savings-total')).toHaveAttribute('data-won', '105000000')
  await dialog.getByRole('button', { name: '취소' }).click()
  expect((await (await request.get('/api/retirement')).json()).plan).toEqual(initial.plan)
})

test('개인연금: 저장 충돌은 최신 계획을 덮지 않고 초안을 유지한다', async ({ page, request }) => {
  const initial = await seed(request)
  await page.goto('/#pension')
  await page.getByRole('button', { name: '미래 납입 계획', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '개인연금 미래 납입 계획' })
  await expect(dialog.getByRole('button', { name: '나 계획 저장' })).toBeEnabled()
  const updated = await request.put('/api/retirement/plan', { data: { ...initial.plan, monthly_need: 4000000 } })
  expect(updated.ok()).toBe(true)
  await dialog.getByRole('button', { name: '나 계획 저장' }).click()
  await expect(dialog.getByRole('alert')).toContainText('저장하지 못했어요')
  await expect(dialog.getByLabel('매년 납입할 금액')).toHaveValue('600')
  const after = await (await request.get('/api/retirement')).json()
  expect(after.plan.monthly_need).toBe(4000000)
  expect(after.plan.me.savings_annual).toBe(0)
})

test('개인연금: 1회 납입 효과와 기존 적립금·합계를 나누고 장부는 보존한다', async ({ page, request }, testInfo) => {
  const initial = await seed(request)
  const created = await request.post('/api/assets', { data: { request_id: randomUUID(), name: '납입 분해 검수', account: '납입 분해 검수', owner: 'me', pocket: 'retirement', assetClass: 'mixed', amount: 60000000, pension_layer: 3, as_of: '2026-11-01' } })
  expect(created.ok()).toBe(true)
  const asset = await created.json()
  try {
    const assets = await (await request.get('/api/assets')).json()
    await page.goto('/#pension')
    await page.getByRole('button', { name: '미래 납입 계획', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: '개인연금 미래 납입 계획' })
    await dialog.getByLabel('납입 종료 나이').fill('41')
    await expect(dialog.getByTestId('savings-period')).toHaveText(`${initial.base_year + 1}년 · 매년 1회, 총 1회 납입`)
    await expect(dialog.getByTestId('savings-total')).toHaveAttribute('data-won', '6000000')
    const expected = await (await request.post('/api/retirement/preview', { data: { ...initial.plan, me: { ...initial.plan.me, savings_annual: 6000000, savings_start_year: initial.base_year + 1, savings_end_age: 41 } } })).json()
    const parts = expected.savings_plans.me
    for (const [testId, field] of [['savings-balance-now', 'balance_now'], ['savings-existing-principal', 'existing_principal'], ['savings-existing-monthly', 'existing_monthly_real'], ['savings-added-principal', 'contribution_principal'], ['savings-added-monthly', 'contribution_monthly_real'], ['savings-principal', 'principal'], ['savings-monthly', 'monthly_real']]) {
      await expect(dialog.getByTestId(testId)).toHaveAttribute('data-won', String(parts[field]))
    }
    await expect(dialog.getByRole('row', { name: /이번 납입 효과/ })).toContainText('+')
    for (const width of [1440, 390, 360]) {
      await page.setViewportSize({ width, height: 1100 })
      expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
      expect(await dialog.getByRole('table').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
      await expect(dialog.getByTestId('savings-added-monthly')).toBeVisible()
      await expect(dialog.getByTestId('savings-existing-monthly')).toBeVisible()
      await expect(dialog.getByTestId('savings-monthly')).toBeVisible()
      if (width !== 360) await dialog.screenshot({ path: testInfo.outputPath(`savings-breakdown-${width}.png`) })
    }
    await dialog.getByLabel('매년 납입할 금액').fill('0')
    await expect(dialog.getByTestId('savings-added-principal')).toHaveAttribute('data-won', '0')
    await expect(dialog.getByTestId('savings-added-monthly')).toHaveAttribute('data-won', '0')
    await expect(dialog.getByTestId('savings-monthly')).toHaveAttribute('data-won', String(parts.existing_monthly_real))
    await dialog.getByLabel('매년 납입할 금액').fill('600')
    await expect(dialog.getByTestId('savings-monthly')).toHaveAttribute('data-won', String(parts.monthly_real))
    await dialog.getByRole('button', { name: '나 계획 저장' }).click()
    await expect(dialog).toBeHidden()
    expect(await (await request.get('/api/assets')).json()).toEqual(assets)
    const saved = await (await request.get('/api/retirement')).json()
    expect(saved.savings_plans.me).toEqual(parts)
  } finally {
    expect((await request.delete(`/api/assets/${asset.id}?version=${asset.version}`)).ok()).toBe(true)
  }
})
