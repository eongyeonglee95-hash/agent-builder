import { expect, test, type APIRequestContext } from '@playwright/test'
import { randomUUID } from 'node:crypto'

async function seed(request: APIRequestContext, annual = 0) {
  const family = await (await request.get('/api/family')).json()
  expect((await request.put('/api/family', { data: { me: { name: '납입 계획 검수', age: 40 }, partner: { name: '배우자', age: 43 }, retirement_age: 60, version: family?.version ?? 0 } })).ok()).toBe(true)
  const before = await (await request.get('/api/retirement')).json()
  const response = await request.put('/api/retirement/plan', { data: { me: { private_start_age: 60, savings_annual: annual }, partner: { private_start_age: 63 }, return_rate: .05, inflation: .02, version: before.plan.version } })
  expect(response.ok()).toBe(true)
  return response.json()
}

test('개인연금: 새 초안·미리보기·취소·저장·재진입과 현재 자산 보존', async ({ page, request }) => {
  const initial = await seed(request)
  await page.goto('/#pension')
  const open = page.getByRole('button', { name: '미래 납입 계획', exact: true })
  await expect(open).toHaveCount(1)
  await open.click()
  const dialog = page.getByRole('dialog', { name: '개인연금 미래 납입 계획' })
  await expect(page.getByRole('button', { name: '색상 변경', exact: true })).toBeHidden()
  await expect(dialog.getByLabel('매년 납입할 금액')).toHaveValue('600')
  await expect(dialog.getByLabel('납입 시작 연도')).toHaveValue(String(initial.base_year + 1))
  await expect(dialog.getByLabel('납입 종료 나이')).toHaveValue('55')
  await expect(dialog.getByTestId('savings-period')).toContainText('총 15회 납입')
  await expect(dialog.getByTestId('savings-total')).toHaveAttribute('data-won', '90000000')
  for (const width of [1440, 390, 360]) {
    await page.setViewportSize({ width, height: 900 })
    expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
    await expect(dialog.getByRole('button', { name: '나 계획 저장' })).toBeEnabled()
    if (process.env.RETIRE_SAVINGS_CAPTURE) await dialog.screenshot({ path: `/private/tmp/savings-plan-${width}.png` })
  }
  await dialog.getByRole('button', { name: '취소' }).click()
  await expect(open).toBeFocused()
  await expect(page.getByRole('button', { name: '색상 변경', exact: true })).toBeVisible()
  expect((await (await request.get('/api/retirement')).json()).plan).toEqual(initial.plan)
  await open.click()
  await dialog.getByLabel('납입 시작 연도').fill(String(initial.base_year + 3))
  await expect(dialog.getByTestId('savings-total')).toHaveAttribute('data-won', '78000000')
  const principal = await dialog.getByTestId('savings-principal').getAttribute('data-won')
  const monthly = await dialog.getByTestId('savings-monthly').getAttribute('data-won')
  await dialog.getByRole('button', { name: '나 계획 저장' }).click()
  await expect(dialog).toBeHidden()
  const saved = await (await request.get('/api/retirement')).json()
  expect(String(saved.savings_plans.me.principal)).toBe(principal)
  expect(String(saved.savings_plans.me.monthly_real)).toBe(monthly)
  expect(saved.plan.partner).toEqual(initial.plan.partner)
  expect(saved.capital).toEqual(initial.capital)
  await expect(page.getByTestId('layer-monthly-3')).toHaveAttribute('data-won', monthly!)
  await page.reload()
  await open.click()
  await expect(dialog.getByLabel('납입 시작 연도')).toHaveValue(String(initial.base_year + 3))
  await dialog.getByLabel('매년 납입할 금액').fill('0')
  await expect(dialog.getByTestId('savings-total')).toHaveAttribute('data-won', '0')
  await dialog.getByRole('button', { name: '나 계획 저장' }).click()
  await expect(dialog).toBeHidden()
  await open.click()
  await expect(dialog.getByLabel('매년 납입할 금액')).toHaveValue('0')
})

