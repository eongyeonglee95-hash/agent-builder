import { randomUUID } from 'node:crypto'
import { expect, test } from '@playwright/test'

test.afterEach(async ({ request }) => {
  const assets = await (await request.get('/api/assets')).json()
  for (const asset of assets.filter((a: any) => a.account.startsWith('검수 계좌 '))) {
    expect((await request.delete(`/api/assets/${asset.id}?version=${asset.version}`)).ok()).toBe(true)
  }
})

test('수령정보: 60세 기본 가정·나이 변경·취소·저장·복원·배우자 설정 보존', async ({ page, request }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const family = await (await request.get('/api/family')).json()
  expect((await request.put('/api/family', { data: { me: { name: '수령 검수', age: 40 }, partner: { name: '배우자 검수', age: 42 }, retirement_age: 62, target_amount: null, version: family?.version ?? 0 } })).ok()).toBe(true)
  const initial = await (await request.get('/api/retirement')).json()
  expect((await request.put('/api/retirement/plan', { data: { ...initial.plan, me: { ...initial.plan.me, private_start_age: null }, partner: { ...initial.plan.partner, private_start_age: 65 }, return_rate: 0, inflation: 0 } })).ok()).toBe(true)
  for (const layer of [3, 4]) expect((await request.post('/api/assets', { data: { request_id: randomUUID(), name: `검수 연금 ${layer}`, account: `검수 계좌 ${layer}`, owner: 'me', pocket: 'retirement', assetClass: 'mixed', amount: 36000000, pension_layer: layer, as_of: '2026-11-01' } })).ok()).toBe(true)
  const before = await (await request.get('/api/retirement')).json()
  await page.goto('/#pension')
  await page.getByRole('group', { name: '연금 조회 범위' }).getByRole('button', { name: '나', exact: true }).click()
  const personal = page.getByRole('button', { name: '3층 개인연금 살펴보기', exact: true })
  const extra = page.getByRole('button', { name: '4층 추가연금 살펴보기', exact: true })
  await expect(personal).toContainText('나 60세부터 · 30년 수령 · 기본 가정')
  await expect(extra).toContainText('나 60세부터 · 30년 수령 · 기본 가정')
  await extra.click()
  await expect(page.locator('.tower-member').first()).toContainText('수령정보 미입력 · 60세 기본 가정')
  await page.getByRole('button', { name: '추가연금 수령 설정', exact: true }).click()
  let dialog = page.getByRole('dialog')
  await expect(dialog.getByTestId('payout-period-me')).toContainText('60세부터 90세 직전까지 · 30년')
  await dialog.getByRole('button', { name: '65세', exact: true }).click()
  await expect(dialog.getByTestId('payout-period-me')).toContainText('65세부터 90세 직전까지 · 25년')
  await dialog.getByRole('spinbutton', { name: '나 사적연금 개시 나이', exact: true }).fill('63')
  await dialog.getByRole('button', { name: '취소', exact: true }).click()
  expect((await (await request.get('/api/retirement')).json()).plan).toEqual(before.plan)
  await personal.click()
  await page.getByRole('button', { name: '개인연금 수령 설정', exact: true }).click()
  dialog = page.getByRole('dialog')
  for (const width of [1440, 390, 360]) {
    await page.setViewportSize({ width, height: 1000 })
    expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
    if (width !== 360) await dialog.screenshot({ path: testInfo.outputPath(`payout-${width}.png`) })
  }
  await dialog.getByRole('button', { name: '55세', exact: true }).click()
  await dialog.getByRole('button', { name: '저장하고 다시 계산', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(personal).toContainText('나 55세부터 · 35년 수령 · 직접 설정')
  const saved = await (await request.get('/api/retirement')).json()
  expect(saved.plan.me.private_start_age).toBe(55)
  expect(saved.plan.partner).toEqual(before.plan.partner)
  expect(saved.projection.summary.streams.filter((s: any) => s.person === 'me' && [3, 4].includes(s.layer)).every((s: any) => s.start_age === 55)).toBe(true)
  await page.reload()
  await page.getByRole('button', { name: '은퇴·수령 시점', exact: true }).click()
  dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('spinbutton', { name: '나 사적연금 개시 나이', exact: true })).toHaveValue('55')
  await dialog.getByRole('button', { name: '기본값 60세로 되돌리기', exact: true }).first().click()
  await dialog.getByRole('button', { name: '저장하고 다시 계산', exact: true }).click()
  await expect(dialog).toBeHidden()
  const reset = await (await request.get('/api/retirement')).json()
  expect(reset.plan.me.private_start_age).toBeNull()
  expect(reset.used.me.private_start_age).toBe(60)
  expect(reset.plan.partner).toEqual(before.plan.partner)
  expect(errors).toEqual([])
})
