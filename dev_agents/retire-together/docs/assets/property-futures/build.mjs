import fs from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
const dir=path.dirname(fileURLToPath(import.meta.url));
const target=path.resolve(dir,'../../../web/public/previews/property-futures.html');
let html=await fs.readFile(target,'utf8');
const js=(await Promise.all(['prototype.js','market.js','grouping.js','comparison.js'].map(name=>fs.readFile(path.join(dir,name),'utf8')))).join('\n')+'\nrender();';
const css=await fs.readFile(path.join(dir,'quant.css'),'utf8');
new vm.Script(js);
html=html.replace(/<script>[\s\S]*?<\/script>/,()=>`<script>\n${js}\n</script>`);
html=html.replace(/\/\* QUANT START \*\/[\s\S]*?\/\* QUANT END \*\//,'');
html=html.replace('</style>',`/* QUANT START */\n${css}\n/* QUANT END */\n</style>`);
html=html.replace(/<title>[^<]*<\/title>/,'<title>둘이서은퇴 · 서울과 관심 단지 부동산 리서치</title>');
html=html.replace(/<nav class="concept-nav"[\s\S]*?<\/nav>/,'<nav class="concept-nav" aria-label="리서치 화면"><button data-view="market" aria-pressed="true"><span>01</span>시장 · 관심 단지</button><button data-view="relative" aria-pressed="false"><span>02</span>여러 단지 비교</button><button data-view="journal" aria-pressed="false"><span>03</span>주간·월간 저널</button></nav>');
html=html.replace('PROPERTY FUTURES','PROPERTY RESEARCH');
html=html.replace(/Concept collection · 01[–—-]04/,'Research workspace · v2');
html=html.replace('<button data-action="research">서비스 분석과 기능 설계 ↗</button>','<span class="prototype-links"><button data-action="dictionary">지표 정의</button><button data-action="research">조사·설계 ↗</button></span>');
await fs.writeFile(target,html);
console.log(JSON.stringify({bytes:Buffer.byteLength(html),javascript:'parsed',selfContained:true}));
