"""Versioned evaluation brief and typed report contract; no financial calculations."""
from typing import Literal
from pydantic import BaseModel, ConfigDict, Field

VERSION = 'pension-xray-report-v4'

class StrictModel(BaseModel):
    model_config = ConfigDict(extra='forbid')

class Finding(StrictModel):
    title: str = Field(max_length=70)
    evidence: str
    implication: str

class Assessment(StrictModel):
    dimension: Literal['목표 적합성', '집중·중복 위험', '유동성·부채', '은퇴 인출', '충격 대응', '실행 가능성']
    status: Literal['확인됨', '조건부', '판단 보류']
    judgment: str = Field(max_length=140)
    evidence: str
    condition: str

class Alternative(StrictModel):
    name: Literal['박곰희', '올웨더', 'K-올웨더']
    fit: str
    tradeoff: str
    prerequisite: str

class Action(StrictModel):
    timing: Literal['먼저 확인', '다음 결정', '계속 점검']
    action: str
    reason: str
    completion: str

class Question(StrictModel):
    question: str
    impact: str

class AllocationReport(StrictModel):
    headline: str = Field(max_length=60)
    summary: str = Field(max_length=320)
    findings: list[Finding] = Field(min_length=2, max_length=3)
    assessments: list[Assessment] = Field(min_length=6, max_length=6)
    alternatives: list[Alternative] = Field(min_length=3, max_length=3)
    actions: list[Action] = Field(min_length=3, max_length=3)
    questions: list[Question] = Field(min_length=1, max_length=3)

