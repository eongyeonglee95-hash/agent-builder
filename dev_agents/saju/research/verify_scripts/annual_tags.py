EL={'甲':'木','乙':'木','丙':'火','丁':'火','戊':'土','己':'土','庚':'金','辛':'金','壬':'水','癸':'水',
    '子':'水','丑':'土','寅':'木','卯':'木','辰':'土','巳':'火','午':'火','未':'土','申':'金','酉':'金','戌':'土','亥':'水'}
GEN={'木':'火','火':'土','土':'金','金':'水','水':'木'}; KE={'木':'土','土':'水','水':'火','火':'金','金':'木'}
def gods(y):
    hee=[k for k,v in GEN.items() if v==y][0]; gi=[k for k,v in KE.items() if v==y][0]; gu=[k for k,v in GEN.items() if v==gi][0]
    han=[e for e in GEN if e not in (y,hee,gi,gu)][0]
    return {y:('용',2),hee:('희',1),han:('한',0),gu:('구',-1),gi:('기',-2)}
for yong in ('水','土'):
    g=gods(yong); print("용신",yong,{k:v[0] for k,v in g.items()})
    for gz in ['丁未','甲申','乙酉','壬寅','癸卯','甲辰','乙巳','丙午','丁未','戊申','己酉','庚戌','辛亥','壬子','癸丑']:
        s,b=gz; ts,tb=g[EL[s]],g[EL[b]]
        print(f"  {gz} 천간 {ts[0]}({ts[1]:+d}) 지지 {tb[0]}({tb[1]:+d}) 합 {0.5*ts[1]+0.5*tb[1]:+.1f}")
